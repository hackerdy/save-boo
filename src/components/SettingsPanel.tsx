import { useEffect, useRef, useSyncExternalStore } from 'react';
import { ai, DEFAULT_BASE, DEFAULT_MODEL } from '../game/ai';
import { settings, useSettings } from '../game/settings';

interface Props { muted: boolean; onMute: () => void; voiceNote: string; onClose: () => void }

export function SettingsPanel({ muted, onMute, voiceNote, onClose }: Props) {
  const s = useSettings();
  const status = useSyncExternalStore(ai.subscribe, ai.status);
  const box = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const opener = document.activeElement as HTMLElement | null;
    const k = (e: KeyboardEvent) => {
      if (e.key === 'Escape') { onClose(); return; }
      if (e.key !== 'Tab' || !box.current) return;
      const f = Array.from(box.current.querySelectorAll<HTMLElement>('input, button, summary, [tabindex]:not([tabindex="-1"])')).filter((el) => !(el as HTMLInputElement).disabled && el.offsetParent !== null);
      if (!f.length) return;
      const first = f[0], last = f[f.length - 1], cur = document.activeElement;
      if (!box.current.contains(cur)) { e.preventDefault(); first.focus(); }
      else if (e.shiftKey && cur === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && cur === last) { e.preventDefault(); first.focus(); }
    };
    window.addEventListener('keydown', k);
    return () => {
      window.removeEventListener('keydown', k);
      (opener && document.contains(opener) ? opener : document.getElementById('settingsBtn'))?.focus();
    };
  }, [onClose]);
  const row = (id: string, label: string, on: boolean, toggle: () => void) => (
    <label className="setrow" htmlFor={id}>
      <span>{label}</span>
      <input id={id} type="checkbox" role="switch" checked={on} onChange={toggle} />
    </label>
  );
  return (
    <div className="overlay" role="dialog" aria-modal="true" aria-label="Settings">
      <div className="settings" ref={box}>
        <h2>Settings</h2>
        {row('setSound', 'Sound effects and voice', !muted, onMute)}
        {row('setVoice', 'Spoken voice (off = subtitles only)', s.voice, () => settings.set({ voice: !s.voice }))}
        {row('setReduced', 'Reduce motion (no shake, no runaway box, no confetti)', s.reducedMotion, () => settings.set({ reducedMotion: !s.reducedMotion }))}
        {row('setLarge', 'Large captions', s.largeCaptions, () => settings.set({ largeCaptions: !s.largeCaptions }))}
        {row('setLow', 'Low power mode (lighter 3D)', s.lowPower, () => settings.set({ lowPower: !s.lowPower }))}
        {row('setHaptics', 'Vibration feedback', s.haptics, () => settings.set({ haptics: !s.haptics }))}
        {row('setAi', 'AI Mortimer (fresh lines every run)', s.aiEnabled, () => settings.set({ aiEnabled: !s.aiEnabled }))}
        <p className="hint">Lines are generated by a third-party free service. Nothing but game context is sent (trial name, mistake count, time). Your typed confession is sent only if you leave the option on in that trial. Off = scripted lines only, no requests.</p>
        <p className="aistatus" id="aiStatus" role="status">{status === 'live' ? 'AI live' : status === 'off' ? 'AI off (scripted lines)' : 'AI offline (scripted lines)'}</p>
        {s.aiEnabled && (
          <details>
            <summary>Use my own AI endpoint (optional)</summary>
            <p className="hint">Any OpenAI-compatible chat completions API. Saved only in this browser (localStorage), never uploaded or committed. https only. Warning: the key is sent to whatever host you type here, so only use a service you trust.</p>
            <label htmlFor="aiBase">Base URL</label>
            <input id="aiBase" type="text" inputMode="url" autoComplete="off" placeholder={DEFAULT_BASE} value={s.aiBase} onChange={(e) => settings.set({ aiBase: e.target.value.trim() })} />
            <label htmlFor="aiModel">Model</label>
            <input id="aiModel" type="text" autoComplete="off" placeholder={DEFAULT_MODEL} value={s.aiModel} onChange={(e) => settings.set({ aiModel: e.target.value.trim() })} />
            <label htmlFor="aiKey">API key</label>
            <input id="aiKey" type="password" autoComplete="off" placeholder="sk-..." value={s.aiKey} onChange={(e) => settings.set({ aiKey: e.target.value.trim() })} />
          </details>
        )}
        {voiceNote && <p className="hint">{voiceNote}</p>}
        <div className="center"><button id="settingsClose" autoFocus onClick={onClose}>Close</button></div>
      </div>
    </div>
  );
}
